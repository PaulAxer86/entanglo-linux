//! System tray icon with Show and Quit actions, using the desktop's
//! StatusNotifier service. Desktops without one simply get no icon, and
//! closing the window then quits as usual.

use std::sync::atomic::{AtomicBool, Ordering};
use std::time::Duration;

use adw::prelude::*;
use ksni::menu::StandardItem;
use ksni::{MenuItem, Tray, TrayMethods};

const TRAY_ID: &str = "com.paoloasara.Entanglo";
/// At login the tray host can appear shortly after this app starts.
const REGISTER_ATTEMPTS: u32 = 15;
const REGISTER_RETRY_DELAY: Duration = Duration::from_secs(2);

static TRAY_ACTIVE: AtomicBool = AtomicBool::new(false);

/// Whether a hidden window can still be reached and the app quit from the tray.
pub fn is_active() -> bool {
    TRAY_ACTIVE.load(Ordering::Relaxed)
}

#[derive(Clone, Copy, Debug)]
enum TrayAction {
    Show,
    Quit,
}

struct EntangloTray {
    actions: async_channel::Sender<TrayAction>,
    icons: Vec<ksni::Icon>,
}

impl EntangloTray {
    fn send(&self, action: TrayAction) {
        let _ = self.actions.try_send(action);
    }
}

impl Tray for EntangloTray {
    fn id(&self) -> String {
        TRAY_ID.into()
    }

    fn title(&self) -> String {
        "Entanglo".into()
    }

    /// Empty, so the tray host draws the monochrome pixmaps instead of
    /// looking up the colored app badge in the icon theme.
    fn icon_name(&self) -> String {
        String::new()
    }

    fn icon_pixmap(&self) -> Vec<ksni::Icon> {
        self.icons.clone()
    }

    fn activate(&mut self, _x: i32, _y: i32) {
        self.send(TrayAction::Show);
    }

    fn menu(&self) -> Vec<MenuItem<Self>> {
        vec![
            StandardItem {
                label: "Show Entanglo".into(),
                activate: Box::new(|tray: &mut Self| tray.send(TrayAction::Show)),
                ..Default::default()
            }
            .into(),
            MenuItem::Separator,
            StandardItem {
                label: "Quit Entanglo".into(),
                icon_name: "application-exit".into(),
                activate: Box::new(|tray: &mut Self| tray.send(TrayAction::Quit)),
                ..Default::default()
            }
            .into(),
        ]
    }
}

/// Registers the tray icon and routes its actions to the application. A window
/// that started hidden is shown if no tray ever becomes available.
pub fn start(
    app: &adw::Application,
    window: &adw::ApplicationWindow,
    handle: &tokio::runtime::Handle,
    started_hidden: bool,
) {
    let (action_tx, action_rx) = async_channel::unbounded();
    let (failed_tx, failed_rx) = async_channel::bounded::<()>(1);

    handle.spawn(async move {
        for attempt in 1..=REGISTER_ATTEMPTS {
            match (EntangloTray { actions: action_tx.clone(), icons: tray_icons() }).spawn().await {
                Ok(tray_handle) => {
                    TRAY_ACTIVE.store(true, Ordering::Relaxed);
                    tracing::info!("system tray icon registered");
                    // Holding the handle for the app's lifetime keeps the icon.
                    std::future::pending::<()>().await;
                    drop(tray_handle);
                }
                Err(error) => {
                    tracing::debug!(%error, attempt, "system tray not available yet");
                    tokio::time::sleep(REGISTER_RETRY_DELAY).await;
                }
            }
        }
        tracing::info!("no system tray available");
        let _ = failed_tx.send(()).await;
    });

    if started_hidden {
        let window = window.clone();
        glib::spawn_future_local(async move {
            if failed_rx.recv().await.is_ok() {
                window.present();
            }
        });
    }

    let window = window.clone();
    let app = app.clone();
    glib::spawn_future_local(async move {
        while let Ok(action) = action_rx.recv().await {
            match action {
                TrayAction::Show => window.present(),
                TrayAction::Quit => app.quit(),
            }
        }
    });
}

/// The rabbit glyph as ARGB32 pixmaps in the panel's text color, like the
/// desktop's own status icons. Generated by `scripts/make-tray-icons.py`.
fn tray_icons() -> Vec<ksni::Icon> {
    let sources: [&'static [u8]; 4] = [
        include_bytes!("../data/icons/tray/tray-22.png"),
        include_bytes!("../data/icons/tray/tray-32.png"),
        include_bytes!("../data/icons/tray/tray-48.png"),
        include_bytes!("../data/icons/tray/tray-64.png"),
    ];
    let [red, green, blue] = panel_foreground();
    sources
        .iter()
        .filter_map(|bytes| {
            let pixbuf = gtk::gdk_pixbuf::Pixbuf::from_read(std::io::Cursor::new(*bytes)).ok()?;
            let pixbuf = if pixbuf.has_alpha() { pixbuf } else { pixbuf.add_alpha(false, 0, 0, 0).ok()? };
            let (width, height, stride) = (pixbuf.width(), pixbuf.height(), pixbuf.rowstride() as usize);
            let pixels = pixbuf.read_pixel_bytes();
            let mut data = Vec::with_capacity((width * height * 4) as usize);
            for y in 0..height as usize {
                for x in 0..width as usize {
                    data.extend_from_slice(&[pixels[y * stride + x * 4 + 3], red, green, blue]);
                }
            }
            Some(ksni::Icon { width, height, data })
        })
        .collect()
}

/// The text color of the desktop's window color scheme, which Plasma panels
/// follow: light on Breeze Dark, dark on Breeze. White without a KDE color
/// scheme, matching the dark top bars of most other desktops.
fn panel_foreground() -> [u8; 3] {
    let config = std::env::var_os("XDG_CONFIG_HOME").map(std::path::PathBuf::from)
        .or_else(|| std::env::var_os("HOME").map(|home| std::path::Path::new(&home).join(".config")));
    config
        .and_then(|dir| std::fs::read_to_string(dir.join("kdeglobals")).ok())
        .and_then(|text| kde_window_foreground(&text))
        .unwrap_or([255, 255, 255])
}

fn kde_window_foreground(kdeglobals: &str) -> Option<[u8; 3]> {
    let mut in_window = false;
    for line in kdeglobals.lines().map(str::trim) {
        if line.starts_with('[') {
            in_window = line == "[Colors:Window]";
        } else if let Some(value) = line.strip_prefix("ForegroundNormal=").filter(|_| in_window) {
            let parts: Vec<u8> = value.split(',').filter_map(|part| part.trim().parse().ok()).collect();
            return (parts.len() >= 3).then(|| [parts[0], parts[1], parts[2]]);
        }
    }
    None
}

#[cfg(test)]
mod icon_tests {
    use super::kde_window_foreground;

    #[test]
    fn reads_the_window_text_color_only() {
        let text = "[Colors:Button]\nForegroundNormal=1,2,3\n\n[Colors:Window]\nBackgroundNormal=32,35,38\nForegroundNormal=252,252,252\n";
        assert_eq!(kde_window_foreground(text), Some([252, 252, 252]));
        assert_eq!(kde_window_foreground("[General]\nForegroundNormal=1,2,3\n"), None);
        assert_eq!(kde_window_foreground("[Colors:Window]\nForegroundNormal=bad\n"), None);
    }
}
